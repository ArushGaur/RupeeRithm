import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { inflate, sipFor, sipFV, equityAt } from '../lib/planning.js';
import { riskProfile } from '../lib/risk.js';
import { checkRequest, checkSuitability, scanOutput, DISCLOSURE } from '../lib/guardrails.js';
import { buildPortfolio, maxDrawdown } from '../lib/portfolio.js';
import { answer } from '../lib/research.js';
const personas = JSON.parse(fs.readFileSync('data/personas.json', 'utf8'));
test('inflation', () => assert.ok(Math.abs(inflate(3000000, 0.08, 15) - 9516507) < 200));
test('SIP round trip', () => assert.ok(Math.abs(sipFV(sipFor(9516507, 0.12, 15), 0.12, 15) - 9516507) < 1));
test('glide path falls', () => assert.ok(equityAt(80, 1) < equityAt(80, 5) && equityAt(80, 12) === 80));
test('maxDrawdown', () => assert.ok(Math.abs(maxDrawdown([100, 120, 90, 110]) + 0.25) < 1e-9));
test('guarantee blocked', () => assert.equal(checkRequest('guarantee me 20%').blocked, true));
test('retiree small-cap flagged', () => { const c = personas.find((p) => p.id === 'retiree'); assert.ok(checkSuitability(c, riskProfile(c), 'only small-cap').length > 0); });
test('trader: lower of capacity/tolerance', () => { const p = riskProfile(personas.find((x) => x.id === 'trader')); assert.equal(p.final, Math.min(p.capacity, p.tolerance)); assert.ok(p.final < 5); });
test('weights sum to 1', () => { const w = buildPortfolio(60).picks.reduce((a, p) => a + p.weight, 0); assert.ok(Math.abs(w - 1) < 1e-9); });
test('research refuses unknown', () => assert.equal(answer('who won the cricket world cup').found, false));
test('research cites', () => assert.equal(answer('What is the exit load?').citations.length, 1));
test('disclosure text passes the output scan', () => assert.doesNotThrow(() => scanOutput(JSON.stringify({ disclosure: DISCLOSURE }))));
test('guarantee language in content is still blocked', () => assert.throws(() => scanOutput(JSON.stringify({ x: 'guaranteed returns', disclosure: DISCLOSURE }))));
